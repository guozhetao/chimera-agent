from __future__ import annotations

import math
from typing import Any

from ..data.dataset import Case
from ..features.text import text_signal_features


class ReasoningGenerator:
    def generate(self, case: Case, prediction: str, probability: float) -> dict[str, Any]:
        if case.task == 1:
            return self._task1(case, prediction, probability)
        if case.task == 2:
            return self._task2(case, prediction, probability)
        raise ValueError("Task 3 reasoning is generated by SurvivalReasoningGenerator")

    def _confidence(self, probability: float, conflict: bool = False, missing: bool = False) -> str:
        if missing or probability < 0.50:
            return "uncertain"
        if conflict or 0.50 <= probability < 0.65:
            return "borderline"
        return "clear"

    def _task1(self, case: Case, prediction: str, probability: float) -> dict[str, Any]:
        p = case.prompt
        pirads = p.get("pirads")
        psa = p.get("psa")
        psad = p.get("psad")
        prior_bx = p.get("bx")
        signals = text_signal_features(case)
        prior_isup = signals.get("txt_prior_isup_max")
        known_cancer = (
            str(prior_bx) == "Positive"
            or (prior_isup is not None and math.isfinite(prior_isup))
            or signals.get("txt_positive_biopsy", 0) > 0
        )
        rule = "yes" if str(pirads) in {"4", "5"} else "no"
        weights = {
            "pirads": "decisive" if str(pirads) in {"4", "5"} and prediction == "yes" else "important",
            "psa": "important" if psa is not None and float(psa) >= 4.0 else "noted",
            "psad": "important" if psad is not None and float(psad) >= 0.15 else "noted",
            "vol": "noted",
            "dre": "important" if p.get("dre") in {"Abnormal", "Suspicious", "Nodus"} else "noted",
            "fh": "noted",
            "comorbidity": "noted",
            "age": "important",
            "bx": "important" if prior_bx in {"Positive", "Negative"} else "noted",
            "cspca": "important" if p.get("cspca") is not None and float(p.get("cspca")) >= 0.85 else "not_used",
        }
        findings = f"PI-RADS {pirads}, PSA {psa} ng/mL, and PSA density {psad} ng/mL/mL"
        if prediction == "yes":
            rationale = (
                f"Biopsy is recommended. The MRI shows {findings}. "
                "Under EAU-style diagnostic guidance, a suspicious PI-RADS lesion together with elevated PSA or PSA density "
                "justifies prostate biopsy before histopathological confirmation. "
                f"Prior biopsy status is {prior_bx or 'not reported'}; it was considered but does not remove the need to "
                "characterise the current lesion."
            )
        elif known_cancer:
            prior_grade = (
                f"prior ISUP grade group {int(prior_isup)}"
                if prior_isup is not None and math.isfinite(prior_isup)
                else "a prior positive biopsy"
            )
            rationale = (
                f"Biopsy is not recommended at this stage. The patient already has an established diagnosis from {prior_grade}, "
                f"and the current assessment shows {findings}. The immediate priority is staging and definitive treatment rather "
                "than further sampling; repeat biopsy would be reconsidered only if it could change the treatment plan."
            )
        else:
            rationale = (
                f"Biopsy is not recommended at this time. The MRI shows {findings}. "
                "Although the lesion is visible, the overall balance of PSA density, prior biopsy history, comorbidity, and "
                "patient preference does not favour immediate repeat biopsy. Short-interval PSA follow-up and repeat MRI are "
                "reasonable, with biopsy reserved for progression or a new suspicious lesion."
            )
        return {
            "confidence": self._confidence(probability, prediction != rule, pirads in {None, "NA"}),
            "variable_weights": weights,
            "reveal_sequence": ["radiology_report"],
            "free_text": rationale,
        }

    def _task2(self, case: Case, prediction: str, probability: float) -> dict[str, Any]:
        from ..features.pathology_parser import parse_pathology

        p = case.prompt
        isup = p.get("bx_isup")
        gl1, gl2 = p.get("bx_gl_prim"), p.get("bx_gl_sec")
        findings = parse_pathology(case.clinical.get("pathology_report"))
        cribriform = findings.cribriform or findings.intraductal
        stable = text_signal_features(case).get("txt_stable_language", 0.0) > 0
        weights = {
            "pirads": "important" if str(p.get("pirads")) in {"4", "5"} else "noted",
            "psa": "important",
            "psad": "important" if p.get("psad") is not None and float(p.get("psad")) >= 0.15 else "noted",
            "age": "important" if prediction == "watchful_waiting" else "noted",
            "comorbidity": "important" if prediction == "watchful_waiting" else "noted",
            "fh": "noted",
            "ct": "important" if str(p.get("ct", "")).startswith("cT2") or str(p.get("ct", "")).startswith("cT3") else "noted",
            "cspca": "important" if cribriform else "noted",
        }
        if isup is not None:
            weights.update({
                "bx_isup": "decisive" if isup in {2, 3, 4, 5} else "important",
                "bx_gl_prim": "important",
                "bx_gl_sec": "important" if (gl2 or 0) >= 4 or cribriform else "noted",
            })
        grade = (
            f"ISUP grade group {isup} with Gleason {gl1}+{gl2}"
            if isup is not None
            else "a biopsy grade that was not fully reported"
        )
        display = prediction.replace("_", " ")
        if prediction == "active_surveillance":
            rationale = (
                f"Biopsy shows {grade}, consistent with favorable-risk disease. Together with the MRI findings, PSA density, "
                "and the existing surveillance pathway, EAU/NCCN-style criteria support active surveillance with protocol MRI, "
                "PSA monitoring, and repeat biopsy."
            )
        elif prediction == "active_treatment":
            rationale = (
                f"Biopsy shows {grade}, consistent with unfavorable intermediate- or higher-risk disease. "
                "Higher-grade disease, adverse pathology, and/or clinically significant MRI findings support definitive "
                "active treatment rather than continued surveillance."
            )
        elif prediction == "continued_surveillance":
            rationale = (
                f"The available biopsy result is negative or low grade ({grade}). With the current MRI and PSA trajectory, "
                "continued surveillance without immediate intervention is appropriate."
            )
        else:
            rationale = (
                f"Although biopsy shows {grade}, age and comorbidity suggest a limited benefit from curative intervention. "
                "A symptom-directed watchful-waiting approach is more consistent with the patient's goals and expected survival."
            )
        if stable and prediction in {"active_surveillance", "continued_surveillance"}:
            rationale += " Multiple biopsy timepoints were histologically stable, supporting surveillance."
        if cribriform and prediction == "active_treatment":
            rationale += " Cribriform morphology is an adverse feature and argues against delaying treatment."
        if cribriform and prediction in {"active_surveillance", "continued_surveillance"}:
            rationale += " Cribriform morphology was noted and warrants close follow-up."
        return {
            "confidence": "borderline" if 0.45 <= probability < 0.68 else "clear",
            "variable_weights": weights,
            "reveal_sequence": [],
            "free_text": (
                f"The recommendation is {display}. PI-RADS is {p.get('pirads')}, PSA is {p.get('psa')} ng/mL, "
                f"PSA density is {p.get('psad')} ng/mL/mL, and clinical stage is {p.get('ct')}. {rationale}"
            ),
        }


class SurvivalReasoningGenerator:
    def generate(self, case: Case, event_probability: float, predicted_months: float, event: int) -> dict[str, Any]:
        from ..features.pathology_parser import parse_pathology

        clinical = case.clinical
        surgical_text = clinical.get("surgical_pathology_report") or ""
        findings = parse_pathology(surgical_text, surgical=True)
        biopsy = parse_pathology(clinical.get("pathology_report"), surgical=False)
        psa = case.prompt.get("psa")
        age = case.prompt.get("age")

        adverse = []
        if findings.extraprostatic_extension:
            adverse.append("extraprostatic extension")
        if findings.positive_margin:
            adverse.append("positive surgical margins")
        if findings.seminal_vesicle_invasion:
            adverse.append("seminal vesicle invasion")
        if findings.lymph_node_metastasis:
            adverse.append("lymph node metastasis")
        if findings.cribriform or findings.intraductal:
            adverse.append("cribriform or intraductal growth")

        grade = findings.isup_grade_group if findings.isup_grade_group is not None else biopsy.isup_grade_group
        grade_text = f"ISUP grade group {grade}" if grade is not None else "the reported grade"
        stage_text = f"pathological stage {findings.pt_stage}" if findings.pt_stage else "the pathological stage"
        adverse_text = (
            "Adverse features included " + ", ".join(adverse) + "."
            if adverse
            else "No major adverse pathological feature was recorded."
        )

        if event:
            text = (
                f"After radical prostatectomy, {grade_text} disease with {stage_text} and a preoperative PSA of "
                f"{psa} ng/mL places this patient in a higher-risk trajectory. {adverse_text} "
                f"The estimated biochemical-recurrence probability is {event_probability:.2f}, with recurrence expected "
                f"at approximately {predicted_months:.0f} months; close postoperative PSA monitoring is warranted."
            )
        else:
            text = (
                f"After radical prostatectomy, {grade_text} disease with {stage_text} and a preoperative PSA of "
                f"{psa} ng/mL is consistent with a lower-risk trajectory. {adverse_text} "
                f"The estimated biochemical-recurrence probability is {event_probability:.2f}; recurrence is not expected "
                f"within the next {predicted_months:.0f} months, although protocol PSA follow-up remains necessary."
            )

        weights = {
            "age": "noted" if age is not None else "not_used",
            "psa": "important" if psa is not None and float(psa) >= 10 else "noted",
            "isup_grade_group": "decisive" if grade is not None and grade >= 3 else "important",
            "gleason": "important" if findings.gleason_primary is not None else "noted",
            "pt_stage": "important" if findings.pt_stage else "noted",
            "positive_margin": "important" if findings.positive_margin else "noted",
            "extraprostatic_extension": "important" if findings.extraprostatic_extension else "noted",
            "seminal_vesicle_invasion": "important" if findings.seminal_vesicle_invasion else "noted",
            "lymph_node_metastasis": "decisive" if findings.lymph_node_metastasis else "noted",
            "lymphovascular_invasion": "important" if findings.lymphovascular_invasion else "noted",
        }
        return {
            "confidence": "borderline" if 0.35 <= event_probability < 0.65 else "clear",
            "variable_weights": weights,
            "reveal_sequence": ["surgical_pathology_report", "pathology_report", "radiology_report"],
            "free_text": text,
        }
